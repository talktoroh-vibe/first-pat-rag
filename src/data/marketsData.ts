// Generate realistic chart history helper
function generateChartPoints(basePrice: number, points: number, volatility: number, upwardBias: number) {
  const result: { time: string; price: number; volume: number }[] = [];
  let curr = basePrice * (1 - (upwardBias * points * 0.001));
  const now = Date.now();
  const step = 3600 * 1000; // 1 hour step

  for (let i = points; i >= 0; i--) {
    const timeStr = new Date(now - i * step).toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' });
    const change = (Math.random() - 0.48 + upwardBias) * (basePrice * volatility);
    curr = Math.max(curr * 0.8, curr + change);
    const volume = Math.floor(Math.random() * 500000 + 100000);
    result.push({
      time: timeStr,
      price: Number(curr.toFixed(2)),
      volume,
    });
  }
  // Ensure last point matches basePrice closely
  result[result.length - 1].price = basePrice;
  return result;
}

